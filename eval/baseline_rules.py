#!/usr/bin/env python3
"""The rule-based baseline of A-M2(ii), scored beside the fine-tuned models.

`eval/rule_parser.py` is a keyword and regex parser with number-word normalisation,
written and tuned on the training split alone (its docstring says how). This script
runs it on the three test splits and on Exp-3's speech-recognised transcripts, and
writes the tables of `eval/baseline_report.py` with the three fine-tuned models at the
deployed quantisation (Q4_K_M, grammar on) as comparison rows.

The parser needs no model, so there is no server and no host dependence: the same
transcript always gives the same command. Its EM on the training split is printed for
reference, because a rule set that only fits its development data would show it here
first.

Usage:
    python eval/baseline_rules.py
"""

from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):  # `python eval/baseline_rules.py`
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eval import baseline_report as br
from eval.rule_parser import parse

REPO = Path(__file__).resolve().parent.parent
PREDS = REPO / "results" / "baseline_rules_preds"
OUT_MD = REPO / "results" / "baseline_rules.md"
NAME = "Rule-based parser"


def run_text() -> None:
    for split in ("train", *br.SPLITS):
        rows = [{"id": r["id"], "transcript": r["transcript"], "gold": r["target"],
                 "raw": parse(r["transcript"])} for r in br.split_items(split)]
        br.write_jsonl(PREDS / f"{split}.jsonl", rows)


def main() -> int:
    br.quiet()
    run_text()
    br.run_asr(parse, PREDS / "asr")

    train = br.predictions_from_rows(br.read_jsonl(PREDS / "train.jsonl"))
    train_em = sum(p.correct for p in train.values()) / len(train)

    systems = {NAME: {s: br.predictions_from_rows(br.read_jsonl(PREDS / f"{s}.jsonl"))
                      for s in br.SPLITS}}
    for stem in br.FINE_TUNED:
        systems[br.SHORT[stem]] = {s: br.fine_tuned_predictions(stem, s) for s in br.SPLITS}
    reference = br.SHORT[br.DEPLOYED]

    asr = {NAME: PREDS / "asr", reference: br.ASR_ARTEFACTS / br.DEPLOYED,
           br.SHORT[br.FINE_TUNED[1]]: br.ASR_ARTEFACTS / br.FINE_TUNED[1],
           br.SHORT[br.FINE_TUNED[2]]: br.ASR_ARTEFACTS / br.FINE_TUNED[2]}

    lines = [
        "### Rule-based baseline against the fine-tuned models (A-M2 ii)",
        "",
        "Generated by `python eval/baseline_rules.py`. Do not edit by hand.",
        "",
        "Parser: `eval/rule_parser.py`, keyword and regex rules with the repository's "
        "number-word normalisation (`eval/norm.py`), written from the training split "
        "only (96 template families, all disjoint from the test families) and frozen before "
        "the first test run. No rule comes from a test, validation or out-of-domain item or "
        "from the generator's vocabulary files; about six test items were seen in file heads "
        "while checking formats. A bug found after the test run is left in (the module "
        "docstring describes it; 2 golden and 1 synthetic items). Its EM on the training "
        "split it was written from: "
        f"**{train_em:.3f}** (n = {len(train)}). Fine-tuned rows: `results/surface_b_preds/`, "
        "`llama.cpp`, grammar on, re-scored here by the same code. Raw predictions: "
        "`results/baseline_rules_preds/`.",
        "",
        *br.text_tables(systems, reference),
        "",
        *br.asr_tables(asr, reference),
    ]
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_MD.relative_to(REPO)}  (train EM {train_em:.3f})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
